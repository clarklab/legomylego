def og_home() -> None:
    W, H = 1200, 630
    img = studs_background(W, H)
    lt = logo_lettering().resize((440, 330), Image.LANCZOS)
    c = card(lt, 28, border=6, shadow=(12, 14)).rotate(3, resample=Image.BICUBIC, expand=True)
    img.paste(c, (50, (H - c.height) // 2 - 4), c)
