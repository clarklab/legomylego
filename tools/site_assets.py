"""Generate the static site's derived assets from the brickkit exports in site/.

Run after exporting models (`python -m brickkit viewer <slug>`):

    .venv/bin/python tools/site_assets.py

Writes (all inside site/):
  favicon.svg, favicon.ico (16/32/48), favicon-32.png, apple-touch-icon.png, icon-192.png,
  icon-512.png, icon-maskable-192.png, icon-maskable-512.png, site.webmanifest
  assets/brand/logo-header.{png,webp}, assets/brand/logo-square.png
  assets/og/home.png and assets/og/<slug>.png          1200x630 link-preview images
  assets/img/<slug>/<render>{,-480}.webp               web-sized copies of the renders
  assets/media.json                                    content hashes + sizes (cache busting)
  m/<slug>/index.html                                  per-model page with its own meta tags
  sitemap.xml
and stamps ?v=<hash> onto image/icon URLs in index.html, model.html and 404.html.

Only Pillow is needed. It is safe to re-run; stale generated pages and images for models that
are no longer in models.json are removed.
"""
