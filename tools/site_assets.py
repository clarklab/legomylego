# ---------------------------------------------------------------- helpers

def sha(path: Path, n: int = 10) -> str:
    return hashlib.sha1(path.read_bytes()).hexdigest()[:n]


def font(size: int, weight: int = 700) -> ImageFont.FreeTypeFont:
    f = ImageFont.truetype(str(FONT), size)
    try:
        f.set_variation_by_axes([weight, 100])
    except Exception:
        pass
    return f


def fmt_cm(mm: float) -> str:
    cm = mm / 10
    return f"{cm:.0f}" if cm >= 100 else f"{cm:.1f}".removesuffix(".0")


def lede(d: dict) -> str:
    """Same wording as ledeFor() in assets/js/model.js."""
    if d.get("description"):
        return d["description"]
    s = f"{d.get('pieces', d['parts']):,} real LEGO parts, about {fmt_cm((d.get('dims_mm') or [0, 0, 0])[1])} cm tall"
    extras = []
    if d.get("mechanism"):
        extras.append("a working mechanism")
    if d.get("lights"):
        extras.append("a built-in light" if len(d["lights"]) == 1 else "built-in lights")
    if extras:
        s += ", with " + " and ".join(extras)
    return s + ". Every part, connection and step checked by computer."


def best_render(renders: list[str]) -> str | None:
    for pat in (r"hero", r"three.?quarter"):
        for r in renders:
            if re.search(pat, r, re.I):
                return r
    return renders[0] if renders else None


def write_if_changed(path: Path, data: bytes | str) -> None:
    b = data.encode() if isinstance(data, str) else data
    if path.exists() and path.read_bytes() == b:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(b)


def save_png(img: Image.Image, path: Path, **kw) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    img.save(path, "PNG", optimize=True, **kw)


def rounded_mask(size: tuple[int, int], radius: int, scale: int = 4) -> Image.Image:
    w, h = size
    m = Image.new("L", (w * scale, h * scale), 0)
    ImageDraw.Draw(m).rounded_rectangle((0, 0, w * scale - 1, h * scale - 1), radius * scale, fill=255)
    return m.resize(size, Image.LANCZOS)


def studs_background(w: int, h: int, pitch: int = 42, r: int = 12) -> Image.Image:
    """Brand yellow with a soft LEGO stud grid (shadow ring + highlight)."""
    s = 2
    img = Image.new("RGB", (w * s, h * s), YELLOW)
    layer = Image.new("RGBA", img.size, (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    P, R = pitch * s, r * s
    for y in range(-P // 2, h * s + P, P):
        for x in range(-P // 2, w * s + P, P):
            d.ellipse((x - R + 3, y - R + 4, x + R + 3, y + R + 4), fill=(140, 95, 0, 34))
            d.ellipse((x - R, y - R, x + R, y + R), fill=(255, 236, 110, 150))
            d.ellipse((x - R + 5, y - R + 5, x + R - 5, y + R - 5), fill=(255, 226, 40, 120))
    img.paste(layer, (0, 0), layer)
    return img.resize((w, h), Image.LANCZOS)


def card(img: Image.Image, radius: int, border: int = 6, shadow: tuple[int, int] = (14, 16)) -> Image.Image:
    """Image in a rounded card with a black outline and a hard offset shadow (the site's sticker look)."""
    w, h = img.size
    W, H = w + border * 2 + shadow[0], h + border * 2 + shadow[1]
    out = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    black = Image.new("RGBA", (w + border * 2, h + border * 2), BLACK + (255,))
    m = rounded_mask(black.size, radius + border)
    out.paste(black, shadow, m)
    out.paste(black, (0, 0), m)
    out.paste(img.convert("RGBA"), (border, border), rounded_mask((w, h), radius))
    return out


def wrap(text: str, f: ImageFont.FreeTypeFont, width: int) -> list[str]:
    words, lines, cur = text.split(), [], ""
    for w in words:
        t = f"{cur} {w}".strip()
        if f.getlength(t) <= width or not cur:
            cur = t
        else:
            lines.append(cur)
            cur = w
    if cur:
        lines.append(cur)
    return lines


def pill(draw: ImageDraw.ImageDraw, xy: tuple[int, int], text: str, f, fg, bg, pad=(22, 12)) -> int:
    x, y = xy
    l, t, r, b = f.getbbox(text)
    w, h = r - l + pad[0] * 2, f.size + pad[1] * 2
    draw.rounded_rectangle((x, y, x + w, y + h), h // 2, fill=bg)
    draw.text((x + pad[0], y + h / 2), text, font=f, fill=fg, anchor="lm")
    return w


