def draw_mark(size: int, rounded: bool = True) -> Image.Image:
    """Raster version of MARK_SVG (drawn at 16x and downsampled). Tiny sizes skip the highlights."""
    S = 16
    k = size * S / 64
    img = Image.new("RGBA", (size * S, size * S), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    if rounded:
        d.rounded_rectangle((0, 0, size * S - 1, size * S - 1), 14 * k, fill=YELLOW)
    else:
        d.rectangle((0, 0, size * S, size * S), fill=YELLOW)
    sw = 4 * k
    d.rounded_rectangle((10 * k - sw / 2, 10 * k - sw / 2, 54 * k + sw / 2, 54 * k + sw / 2), 9 * k + sw / 2, fill=BLACK)
    d.rounded_rectangle((10 * k + sw / 2, 10 * k + sw / 2, 54 * k - sw / 2, 54 * k - sw / 2), 9 * k - sw / 2, fill=RED)
    for cx, cy in ((24, 24), (40, 24), (24, 40), (40, 40)):
        r, s2 = 6.2 * k, 1.6 * k
        if size >= 24:
            d.ellipse((cx * k - r - s2 / 2, cy * k - r - s2 / 2, cx * k + r + s2 / 2, cy * k + r + s2 / 2), fill=(184, 13, 31))
            d.ellipse((cx * k - r + s2 / 2, cy * k - r + s2 / 2, cx * k + r - s2 / 2, cy * k + r - s2 / 2), fill=(255, 90, 104))
            h = 1.8 * k
            d.ellipse(((cx - 2) * k - h, (cy - 2) * k - h, (cx - 2) * k + h, (cy - 2) * k + h), fill=(255, 255, 255, 204))
        else:
            d.ellipse((cx * k - r, cy * k - r, cx * k + r, cy * k + r), fill=(255, 120, 130))
    return img.resize((size, size), Image.LANCZOS)


def logo_square(size: int, content: float = 1.0) -> Image.Image:
    """The logo on its yellow square; content < 1 shrinks the lettering (maskable safe zone)."""
    src = Image.open(LOGO_SRC).convert("RGB")
    crop = src.crop((47, 47, 1207, 1207))                 # trim the empty margin a little
    if content >= 1:
        return crop.resize((size, size), Image.LANCZOS)
    out = Image.new("RGB", (size, size), YELLOW)
    inner = crop.resize((round(size * content), round(size * content)), Image.LANCZOS)
    off = (size - inner.width) // 2
    out.paste(inner, (off, off))
    return out


def logo_lettering() -> Image.Image:
    return Image.open(LOGO_SRC).convert("RGB").crop(LOGO_CROP)


def build_brand() -> None:
    brand = SITE / "assets" / "brand"
    brand.mkdir(parents=True, exist_ok=True)
    if LOGO_SRC != SITE / "assets" / "logo.png":
        write_if_changed(SITE / "assets" / "logo.png", LOGO_SRC.read_bytes())
    lt = logo_lettering()
    hdr = lt.resize((128, 96), Image.LANCZOS)
    save_png(hdr, brand / "logo-header.png")
    hdr.save(brand / "logo-header.webp", "WEBP", quality=90, method=6)
    save_png(logo_square(600), brand / "logo-square.png")

    write_if_changed(SITE / "favicon.svg", MARK_SVG)
    sizes = [16, 32, 48]
    ico = [draw_mark(s) for s in sizes]
    ico[-1].save(SITE / "favicon.ico", format="ICO", sizes=[(s, s) for s in sizes], append_images=ico[:-1])
    save_png(draw_mark(32), SITE / "favicon-32.png")
    save_png(logo_square(180), SITE / "apple-touch-icon.png")
    save_png(logo_square(192), SITE / "icon-192.png")
    save_png(logo_square(512), SITE / "icon-512.png")
    save_png(logo_square(192, 0.72), SITE / "icon-maskable-192.png")
    save_png(logo_square(512, 0.72), SITE / "icon-maskable-512.png")


def build_manifest() -> None:
    v = lambda name: f"/{name}?v={sha(SITE / name)}"          # noqa: E731
    manifest = {
        "name": SITE_NAME,
        "short_name": SHORT_NAME,
        "description": SITE_DESC,
        "id": "/",
        "start_url": "/",
        "scope": "/",
        "display": "standalone",
        "background_color": BG_LIGHT,
        "theme_color": THEME,
        "icons": [
            {"src": v("icon-192.png"), "sizes": "192x192", "type": "image/png", "purpose": "any"},
            {"src": v("icon-512.png"), "sizes": "512x512", "type": "image/png", "purpose": "any"},
            {"src": v("icon-maskable-192.png"), "sizes": "192x192", "type": "image/png", "purpose": "maskable"},
            {"src": v("icon-maskable-512.png"), "sizes": "512x512", "type": "image/png", "purpose": "maskable"},
            {"src": v("favicon.svg"), "sizes": "any", "type": "image/svg+xml", "purpose": "any"},
        ],
    }
    write_if_changed(SITE / "site.webmanifest", json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")


